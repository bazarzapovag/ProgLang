    char s = 'A';

    std::cout << "a = " << a;
    std::cout << "b = " << b;
    std::cout << "c = " << c;
    std::cout << "d = " << d;
    std::cout << "e = " << e;
    std::cout << "f = " << f;
    std::cout << "g = " << g;
    std::cout << "h = " << h;
    std::cout << "i = " << i;
    std::cout << "j = " << j;
    std::cout << "k = " << k;
